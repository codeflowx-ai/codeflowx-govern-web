export interface TraceabilityLog {
  id: number;
  type: string;
  timestamp: string;
  description: string;
  hash: string;
  previousHash: string;
  userId: string;
  entityType: string;
  entityId: number;
  integrityVerified: boolean;
}

export interface HitlDecision {
  id: number;
  type: string;
  decision: string;
  timestamp: string;
  userId: string;
  entityType: string;
  entityId: number;
  notes?: string;
}

export interface ModelOutput {
  id: number;
  timestamp: string;
  input: string;
  output: string;
  confidence: number;
  modelId: number;
}

export interface IntegrityVerification {
  score: number;
  status: "INTEGRITY_OK" | "INTEGRITY_WARNING" | "INTEGRITY_ERROR";
  verifiedLogs: number;
  totalLogs: number;
  issues?: string[];
}

export interface ModelTraceability {
  model: {
    id: number;
    name: string;
    version: string;
  };
  dataset: {
    id: number;
    name: string;
    version: string;
  };
  logs: TraceabilityLog[];
  decisions: HitlDecision[];
  outputs: ModelOutput[];
  integrityVerification: IntegrityVerification;
}

export interface RelatedEntity {
  type: string;
  id: number;
  name: string;
  relationship: string;
}

export interface EntityTraceability {
  entityType: string;
  entityId: number;
  entityName: string;
  traceability: ModelTraceability;
  relatedEntities: RelatedEntity[];
}

