-- Art. 27 - Fundamental Rights Impact Assessment
-- Fecha: 2 nov 2025
-- ========================================

-- Tabla FRIAFUNDAMENTALRIGHTSASSESSMENTS (si no existe)
CREATE TABLE IF NOT EXISTS FRIAFUNDAMENTALRIGHTSASSESSMENTS (
    -- Primary Key
    IDXFRIAASSESSMENT BIGSERIAL PRIMARY KEY,
    
    -- UUID estándar
    iduuid VARCHAR(36) NOT NULL UNIQUE,
    
    -- Foreign Keys
    IDXPROJECT BIGINT NOT NULL,
    IDXUSER BIGINT,
    
    -- Art. 27.1.a - Descripción Procesos
    FRIAPROCESSDESCRIPTION TEXT NOT NULL,
    
    -- Art. 27.1.b - Período y Frecuencia
    FRIAUSAGEPERIOD VARCHAR(200),
    FRIAUSAGEFREQUENCY VARCHAR(200),
    
    -- Art. 27.1.c - Categorías Personas Afectadas
    FRIAAFFECTEDCATEGORIES TEXT,
    FRIAVULNERABLEGROUPSINCLUDED BOOLEAN DEFAULT FALSE,
    
    -- Art. 27.1.d - Riesgos Específicos
    FRIARISKS TEXT NOT NULL,
    
    -- Art. 27.1.e - Supervisión Humana
    FRIAHUMANOVERSIGHT TEXT NOT NULL,
    FRIAHITLENABLED BOOLEAN DEFAULT FALSE,
    
    -- Art. 27.1.f - Medidas Mitigación
    FRIAMITI GATIONMEASURES TEXT NOT NULL,
    
    -- Compliance y Quality
    FRIAART27COMPLIANT BOOLEAN DEFAULT FALSE,
    FRIACOMPLETENESSCORE NUMERIC(5,2),
    FRIAQUALSCORE NUMERIC(5,2),
    
    -- Charter UE Analysis
    FRIACHARTERARTICLES TEXT,
    FRIAIMPACTSEVERITY VARCHAR(20),
    
    -- Notificación Autoridad (Art. 27.3)
    FRIANOTIFIED BOOLEAN DEFAULT FALSE,
    FRIANOTIFICATIONID VARCHAR(100),
    FRIANOTIFICATIONDATE TIMESTAMP,
    
    -- Documentación Generada
    FRIADOCUMENTURL VARCHAR(500),
    FRIADOCUMENTVERSION VARCHAR(20),
    
    -- Integración DPIA (Art. 27.4)
    FRIADPIAINTEGRATED BOOLEAN DEFAULT FALSE,
    FRIADPIAID VARCHAR(100),
    
    -- Aprobación
    FRIAAPPROVED BOOLEAN DEFAULT FALSE,
    FRIAAPPROVEDBY BIGINT,
    FRIAAPPROVALDATE TIMESTAMP,
    
    -- Audit Fields
    FRIACREATEDAT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FRIAUPDATEDAT TIMESTAMP
);

-- Comentarios
