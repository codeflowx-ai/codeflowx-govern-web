COMMENT ON COLUMN FRIAFUNDAMENTALRIGHTSASSESSMENTS.FRIACOMPLETENESSCORE IS 'Score de completitud (0-100)';
COMMENT ON COLUMN FRIAFUNDAMENTALRIGHTSASSESSMENTS.FRIAQUALSCORE IS 'Score de calidad (0-100)';
