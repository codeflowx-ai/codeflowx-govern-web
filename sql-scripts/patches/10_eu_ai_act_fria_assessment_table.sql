-- Foreign Keys
ALTER TABLE FRIAFUNDAMENTALRIGHTSASSESSMENTS 
    ADD CONSTRAINT fk_fria_project 
    FOREIGN KEY (IDXPROJECT) REFERENCES PRJPROJECTS(IDXPROJECT) ON DELETE CASCADE;

-- Índices para búsquedas frecuentes
CREATE INDEX IF NOT EXISTS idx_fria_project ON FRIAFUNDAMENTALRIGHTSASSESSMENTS(IDXPROJECT);
CREATE INDEX IF NOT EXISTS idx_fria_deployer ON FRIAFUNDAMENTALRIGHTSASSESSMENTS(IDXUSER);
CREATE INDEX IF NOT EXISTS idx_fria_compliant ON FRIAFUNDAMENTALRIGHTSASSESSMENTS(FRIAART27COMPLIANT);
CREATE INDEX IF NOT EXISTS idx_fria_approved ON FRIAFUNDAMENTALRIGHTSASSESSMENTS(FRIAAPPROVED);
CREATE INDEX IF NOT EXISTS idx_fria_notified ON FRIAFUNDAMENTALRIGHTSASSESSMENTS(FRIANOTIFIED);
CREATE INDEX IF NOT EXISTS idx_fria_severity ON FRIAFUNDAMENTALRIGHTSASSESSMENTS(FRIAIMPACTSEVERITY);
CREATE INDEX IF NOT EXISTS idx_fria_createdat ON FRIAFUNDAMENTALRIGHTSASSESSMENTS(FRIACREATEDAT DESC);

-- Índices GIN para búsquedas en JSONB
CREATE INDEX IF NOT EXISTS idx_fria_affected_gin ON FRIAFUNDAMENTALRIGHTSASSESSMENTS USING GIN(to_tsvector('english', FRIAAFFECTEDCATEGORIES));
CREATE INDEX IF NOT EXISTS idx_fria_risks_gin ON FRIAFUNDAMENTALRIGHTSASSESSMENTS USING GIN(to_tsvector('english', FRIARISKS));

-- Vista para FRIAs pendientes de aprobación
CREATE OR REPLACE VIEW vw_fria_pending_approval AS
SELECT 
    f.IDXFRIAASSESSMENT,
    f.iduuid,
    f.IDXPROJECT,
    p.NAME as project_name,
    f.FRIACOMPLETENESSCORE,
    f.FRIAQUALSCORE,
    f.FRIAIMPACTSEVERITY,
    f.FRIACREATEDAT,
    EXTRACT(DAY FROM (CURRENT_TIMESTAMP - f.FRIACREATEDAT)) as days_pending
FROM FRIAFUNDAMENTALRIGHTSASSESSMENTS f
INNER JOIN PRJPROJECTS p ON f.IDXPROJECT = p.IDXPROJECT
WHERE f.FRIAAPPROVED = FALSE
  AND f.FRIAART27COMPLIANT = TRUE
ORDER BY f.FRIACREATEDAT ASC;

COMMENT ON VIEW vw_fria_pending_approval IS 'FRIAs completas y pendientes de aprobación';

COMMIT;

