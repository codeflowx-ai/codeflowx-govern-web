-- Extensión tabla GOVMODELEVALUATIONS con campos EU AI Act

-- Robustez Adversarial (Art. 15.5)
ALTER TABLE GOVMODELEVALUATIONS ADD COLUMN IF NOT EXISTS EVALADVERSARIALTESTED BOOLEAN DEFAULT FALSE;
COMMENT ON COLUMN GOVMODELEVALUATIONS.EVALADVERSARIALTESTED IS 'Indica si se realizó test adversarial';

ALTER TABLE GOVMODELEVALUATIONS ADD COLUMN IF NOT EXISTS EVALADVERSARIALROBUSTNESS NUMERIC(3,2);
COMMENT ON COLUMN GOVMODELEVALUATIONS.EVALADVERSARIALROBUSTNESS IS 'Score robustez adversarial (0.00-1.00)';

ALTER TABLE GOVMODELEVALUATIONS ADD COLUMN IF NOT EXISTS EVALADVERSARIALRESULTS JSONB;
COMMENT ON COLUMN GOVMODELEVALUATIONS.EVALADVERSARIALRESULTS IS 'Resultados detallados: FGSM, PGD, clases vulnerables, etc.';

-- Feedback Loop Bias (Art. 15.4)
ALTER TABLE GOVMODELEVALUATIONS ADD COLUMN IF NOT EXISTS EVALFEEDBACKLOOPTESTED BOOLEAN DEFAULT FALSE;
COMMENT ON COLUMN GOVMODELEVALUATIONS.EVALFEEDBACKLOOPTESTED IS 'Indica si se testeó feedback loop bias';

ALTER TABLE GOVMODELEVALUATIONS ADD COLUMN IF NOT EXISTS EVALFEEDBACKLOOPBIASSCORE NUMERIC(3,2);
COMMENT ON COLUMN GOVMODELEVALUATIONS.EVALFEEDBACKLOOPBIASSCORE IS 'Score bias feedback loop (0.00-1.00)';

ALTER TABLE GOVMODELEVALUATIONS ADD COLUMN IF NOT EXISTS EVALFEEDBACKLOOPRESULTS JSONB;
COMMENT ON COLUMN GOVMODELEVALUATIONS.EVALFEEDBACKLOOPRESULTS IS 'Resultados detallados feedback loop';

-- Evaluación Integral Compliance
ALTER TABLE GOVMODELEVALUATIONS ADD COLUMN IF NOT EXISTS EVALCOMPLIANCESCORE NUMERIC(3,2);
COMMENT ON COLUMN GOVMODELEVALUATIONS.EVALCOMPLIANCESCORE IS 'Score agregado de compliance (0.00-1.00)';

-- Índices para búsquedas frecuentes
CREATE INDEX IF NOT EXISTS idx_goveval_adversarial ON GOVMODELEVALUATIONS(EVALADVERSARIALTESTED);
CREATE INDEX IF NOT EXISTS idx_goveval_feedbackloop ON GOVMODELEVALUATIONS(EVALFEEDBACKLOOPTESTED);
CREATE INDEX IF NOT EXISTS idx_goveval_compliance ON GOVMODELEVALUATIONS(EVALCOMPLIANCESCORE);

-- Índices GIN para búsquedas en JSONB
CREATE INDEX IF NOT EXISTS idx_goveval_adversarial_gin ON GOVMODELEVALUATIONS USING GIN(EVALADVERSARIALRESULTS);
CREATE INDEX IF NOT EXISTS idx_goveval_feedbackloop_gin ON GOVMODELEVALUATIONS USING GIN(EVALFEEDBACKLOOPRESULTS);

COMMIT;

