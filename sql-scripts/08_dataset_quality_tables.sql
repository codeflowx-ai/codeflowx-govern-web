-- ============================================================================
-- Tabla: DQLDATASETQUALITY
-- Prefijo: DQL (Dataset QuaLity)
-- Descripción: Evaluaciones de calidad de datasets
-- ============================================================================

CREATE TABLE DQLDATASETQUALITY (
    IDUUID UUID DEFAULT gen_random_uuid() UNIQUE,
    IDXDATASETQUALITY BIGSERIAL PRIMARY KEY,
    
    -- Identificación del dataset
    DQLEVALUATIONID VARCHAR(100) UNIQUE NOT NULL,
    DQLDATASETNAME VARCHAR(200) NOT NULL,
    DQLDATASETPATH VARCHAR(500),
    DQLSOURCETYPE VARCHAR(50),
    
    -- Scores principales (0-100)
    DQLOVERALLSCORE DOUBLE PRECISION NOT NULL,
    DQLQUALITYRATING VARCHAR(20),
    
    -- Métricas individuales (0-1)
    DQLCOMPLETENESSCORE DOUBLE PRECISION,
    DQLVALIDITYSCORE DOUBLE PRECISION,
    DQLUNIQUENESSCORE DOUBLE PRECISION,
    DQLCONSISTENCYSCORE DOUBLE PRECISION,
    
    -- Estadísticas del dataset
    DQLTOTALROWS BIGINT,
    DQLTOTALCOLUMNS INTEGER,
    DQLMISSINGPERCENTAGE DOUBLE PRECISION,
    DQLOUTLIERSPERCENTAGE DOUBLE PRECISION,
    DQLDUPLICATESPERCENTAGE DOUBLE PRECISION,
    
    -- Decisión automática (para BPMN)
    DQLDECISION VARCHAR(20) NOT NULL,
    DQLREQUIRESHUMANREVIEW BOOLEAN NOT NULL DEFAULT FALSE,
    DQLJUSTIFICATION TEXT,
    
    -- Issues y recomendaciones (JSON)
    DQLISSUESFOUND JSONB,
    DQLRECOMMENDATIONS JSONB,
    DQLREMEDIATIONSAVAILABLE JSONB,
    
    -- Métricas completas (JSON)
    DQLMETRICSJSON JSONB,
    
    -- Profiling report
    DQLPROFILINGREPORTPATH VARCHAR(500),
    
    -- Metadata
    DQLPROJECTID VARCHAR(100) NOT NULL,
    DQLCREATEDBY VARCHAR(100) NOT NULL,
    DQLCREATEDAT TIMESTAMP NOT NULL DEFAULT NOW(),
    DQLUPDATEDAT TIMESTAMP,
    DQLUPDATEDBY VARCHAR(100),
    
    -- Estado
    DQLSTATUS VARCHAR(20) DEFAULT 'COMPLETED',
    DQLEXECUTIONTIME DOUBLE PRECISION,
    
    -- BPMN Process Instance
    DQLPROCESSINSTANCEID VARCHAR(100)
);

-- Índices
CREATE INDEX IDX_DQLDATASETQUALITY_NAME ON DQLDATASETQUALITY(DQLDATASETNAME);
CREATE INDEX IDX_DQLDATASETQUALITY_PROJECTID ON DQLDATASETQUALITY(DQLPROJECTID);
CREATE INDEX IDX_DQLDATASETQUALITY_DECISION ON DQLDATASETQUALITY(DQLDECISION);
CREATE INDEX IDX_DQLDATASETQUALITY_PROCESSID ON DQLDATASETQUALITY(DQLPROCESSINSTANCEID);
CREATE INDEX IDX_DQLDATASETQUALITY_CREATEDAT ON DQLDATASETQUALITY(DQLCREATEDAT DESC);

-- Comentarios
COMMENT ON TABLE DQLDATASETQUALITY IS 'Evaluaciones de calidad de datasets (Proceso BPMN #13)';
COMMENT ON COLUMN DQLDATASETQUALITY.DQLOVERALLSCORE IS 'Score global de calidad (0-100)';
COMMENT ON COLUMN DQLDATASETQUALITY.DQLDECISION IS 'Decisión: APPROVED, REVIEW_REQUIRED, REJECTED';

-- ============================================================================
-- Tabla: DBLBIASEVALUATION
-- Prefijo: DBL (Dataset Bias evaLuation)
-- Descripción: Evaluaciones de fairness/bias en datasets
-- ============================================================================

CREATE TABLE DBLBIASEVALUATION (
    IDUUID UUID DEFAULT gen_random_uuid() UNIQUE,
    IDXBIASEVALUATION BIGSERIAL PRIMARY KEY,
    
    -- Referencia a dataset quality
    IDXDATASETQUALITY BIGINT REFERENCES DQLDATASETQUALITY(IDXDATASETQUALITY),
    
    -- Identificación
    DBLEVALUATIONID VARCHAR(100) UNIQUE NOT NULL,
    DBLDATASETNAME VARCHAR(200) NOT NULL,
    DBLDATASETPATH VARCHAR(500),
    
    -- Scores
    DBLFAIRNESSSCORE DOUBLE PRECISION NOT NULL,
    DBLBIASSEVERITY VARCHAR(20),
    
    -- Métricas de fairness
    DBLDEMOGRAPHICPARITYDIFF DOUBLE PRECISION,
    DBLDEMOGRAPHICPARITYRATIO DOUBLE PRECISION,
    DBLDISPARATEIMPACT DOUBLE PRECISION,
    DBLEQUALOPPORTUNITYDIFF DOUBLE PRECISION,
    
    -- Atributos protegidos analizados
    DBLPROTECTEDATTRIBUTES JSONB,
    DBLTARGETCOLUMN VARCHAR(100),
    
    -- Decisión
    DBLDECISION VARCHAR(20) NOT NULL,
    DBLREQUIRESHUMANREVIEW BOOLEAN DEFAULT FALSE,
    DBLJUSTIFICATION TEXT,
    
    -- Issues y recomendaciones
    DBLBIASSISSUESFOUND JSONB,
    DBLRECOMMENDATIONS JSONB,
    DBLREMEDIATIONSAVAILABLE JSONB,
    
    -- Métricas completas
    DBLMETRICSJSON JSONB,
    
    -- Metadata
    DBLPROJECTID VARCHAR(100) NOT NULL,
    DBLCREATEDBY VARCHAR(100) NOT NULL,
    DBLCREATEDAT TIMESTAMP NOT NULL DEFAULT NOW(),
    
    -- Estado
    DBLSTATUS VARCHAR(20) DEFAULT 'COMPLETED',
    DBLEXECUTIONTIME DOUBLE PRECISION,
    
    -- BPMN Process Instance
    DBLPROCESSINSTANCEID VARCHAR(100)
);

-- Índices
CREATE INDEX IDX_DBLBIASEVALUATION_DATASETQUALITY ON DBLBIASEVALUATION(IDXDATASETQUALITY);
CREATE INDEX IDX_DBLBIASEVALUATION_PROJECTID ON DBLBIASEVALUATION(DBLPROJECTID);
CREATE INDEX IDX_DBLBIASEVALUATION_SEVERITY ON DBLBIASEVALUATION(DBLBIASSEVERITY);

-- Comentarios
COMMENT ON TABLE DBLBIASEVALUATION IS 'Evaluaciones de fairness/bias en datasets';
COMMENT ON COLUMN DBLBIASEVALUATION.DBLFAIRNESSSCORE IS 'Score de fairness (0-100, mayor es mejor)';

-- ============================================================================
-- Tabla: DPLPIIEVALUATION
-- Prefijo: DPL (Dataset PII evaLuation)
-- Descripción: Evaluaciones de PII (Personal Identifiable Information)
-- ============================================================================

CREATE TABLE DPLPIIEVALUATION (
    IDUUID UUID DEFAULT gen_random_uuid() UNIQUE,
    IDXPIIEVALUATION BIGSERIAL PRIMARY KEY,
    
    -- Referencia a dataset quality
    IDXDATASETQUALITY BIGINT REFERENCES DQLDATASETQUALITY(IDXDATASETQUALITY),
    
    -- Identificación
    DPLEVALUATIONID VARCHAR(100) UNIQUE NOT NULL,
    DPLDATASETNAME VARCHAR(200) NOT NULL,
    DPLDATASETPATH VARCHAR(500),
    
    -- Resultado principal
    DPLPIIFOUND BOOLEAN NOT NULL,
    DPLPIISEVERITY VARCHAR(20),
    DPLTOTALPIIDETECTED INTEGER DEFAULT 0,
    
    -- Distribución de PII
    DPLPIIBYTYPE JSONB,
    DPLPIIBYCOLUMN JSONB,
    DPLPERCENTAGEROWSWITHPII DOUBLE PRECISION,
    
    -- Compliance
    DPLGDPRCOMPLIANT BOOLEAN,
    DPLCOMPLIANCEISSUES JSONB,
    
    -- Decisión
    DPLDECISION VARCHAR(20) NOT NULL,
    DPLREQUIRESHUMANREVIEW BOOLEAN DEFAULT FALSE,
    DPLJUSTIFICATION TEXT,
    
    -- Recomendaciones
    DPLRECOMMENDATIONS JSONB,
    DPLREMEDIATIONSAVAILABLE JSONB,
    
    -- Métricas completas
    DPLMETRICSJSON JSONB,
    
    -- Metadata
    DPLPROJECTID VARCHAR(100) NOT NULL,
    DPLCREATEDBY VARCHAR(100) NOT NULL,
    DPLCREATEDAT TIMESTAMP NOT NULL DEFAULT NOW(),
    
    -- Estado
    DPLSTATUS VARCHAR(20) DEFAULT 'COMPLETED',
    DPLEXECUTIONTIME DOUBLE PRECISION,
    
    -- BPMN Process Instance
    DPLPROCESSINSTANCEID VARCHAR(100)
);

-- Índices
CREATE INDEX IDX_DPLPIIEVALUATION_DATASETQUALITY ON DPLPIIEVALUATION(IDXDATASETQUALITY);
CREATE INDEX IDX_DPLPIIEVALUATION_PROJECTID ON DPLPIIEVALUATION(DPLPROJECTID);
CREATE INDEX IDX_DPLPIIEVALUATION_PIIFOUND ON DPLPIIEVALUATION(DPLPIIFOUND);
CREATE INDEX IDX_DPLPIIEVALUATION_GDPR ON DPLPIIEVALUATION(DPLGDPRCOMPLIANT);

-- Comentarios
COMMENT ON TABLE DPLPIIEVALUATION IS 'Evaluaciones de PII en datasets (GDPR compliance)';
COMMENT ON COLUMN DPLPIIEVALUATION.DPLPIIFOUND IS 'TRUE si se detectó PII en el dataset';
COMMENT ON COLUMN DPLPIIEVALUATION.DPLGDPRCOMPLIANT IS 'TRUE si cumple con GDPR';

